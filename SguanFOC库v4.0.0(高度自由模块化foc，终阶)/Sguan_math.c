// 快速求解反三角tan函数
float Math_atan(float x){
    if (x != x){
      return x;
    }
    if (x < 0.0f){
      return -Math_atan(-x);
    }
    if (x > 1.0f){
      return (float)((float)MATH_Value_PI_2 - (float)Math_atan(1.0f / x));
    }

    float pos = (float)x *90.0f;
    int i = (int)pos;
    if (i >= 90){
      return ATAN_TABLE[90];
    }

    float t = pos - (float)i;
    float y0 = ATAN_TABLE[i];
    float y1 = ATAN_TABLE[i + 1];
    return y0 + (y1 - y0)*t;
}




