static SguanF local_sin_f(SguanF x){
    while (1){
        if (x > VALUE_F_2PI)
            x = x - VALUE_F_2PI;
        else if (x < 0)
            x = x + VALUE_F_2PI;
        else
            break;
    }

    SguanF pos = x * (SguanF)81.487330863050411914;
    int idx0 = (int)pos;
    SguanF frac = pos - (SguanF)idx0;

    if (idx0 > 511){ idx0 = 511; frac = 0.0f; }
    if (idx0 < 0){ idx0 = 0; frac = 0.0f; }

    int idx1 = idx0 + 1;
    if (idx1 >= 512) idx1 = 0;

    return sin_tab[idx0] + (sin_tab[idx1] - sin_tab[idx0]) * frac;
}

// (浮点相关的三角局部函数)
static SguanF local_cos_f(SguanF x){
    return local_sin_f(VALUE_F_PI_2 - x);
}

// (浮点相关的三角局部函数)
static SguanF local_atan_f(SguanF x){
    if (x != x){
      return x;
    }
    if (x < VALUE_F_ZERO){
      return -local_atan_f(-x);
    }
    if (x > VALUE_F_ONE){
      return VALUE_F_PI_2 - local_atan_f(SGUAN_Q(1.0) / x);
    }

    SguanF pos = x*SGUAN_F(90.0);
    int i = (int)pos;
    if (i >= 90){
      return atan_tab[90];
    }

    SguanF t = pos - (SguanF)i;
    SguanF y0 = atan_tab[i];
    SguanF y1 = atan_tab[i + 1];
    return y0 + (y1 - y0)*t;
}

