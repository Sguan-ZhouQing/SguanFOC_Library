// (局部函数q31)
static Q31 __local_q31_mul(Q31 a, Q31 b){
    int64_t result = (int64_t)a * (int64_t)b;
    result += 1LL << 30;
    result >>= 31;

    if (result > __LOCAL_Q31_MAX_64){
        return VALUE_Q31_MAX;
    }
    if (result < __LOCAL_Q31_MIN_64){
        return VALUE_Q31_MIN;
    }
    return (Q31)result;
}

// (局部函数q31)
static Q31 __local_q31_div(Q31 a, Q31 b){
    if (b == 0){
        return (a >= 0) ? VALUE_Q31_MAX : VALUE_Q31_MIN;
    }

    int64_t numerator = (int64_t)a << 31;
    int64_t result = numerator / b;
    int64_t remainder = numerator % b;
    if (remainder != 0){
        int64_t rem_abs = (remainder < 0) ? -remainder : remainder;
        int64_t b_abs = (b < 0) ? -(int64_t)b : (int64_t)b;
        if (rem_abs * 2 >= b_abs){
            result += (numerator >= 0) ? 1 : -1;
        }
    }

    if (result > __LOCAL_Q31_MAX_64){
        return VALUE_Q31_MAX;
    }
    if (result < __LOCAL_Q31_MIN_64){
        return VALUE_Q31_MIN;
    }
    return (Q31)result;
}

// (局部函数q31)
static Q31 __local_q31_convert_base(Q31 q, SguanF old_base, SguanF new_base){
    if (old_base <= VALUE_F_ZERO || new_base <= VALUE_F_ZERO){
        return 0;
    }
    
    SguanF diff = old_base - new_base;
    if ((diff < 0 ? -diff : diff) < 1e-6f) {
        return q;
    }
    
    SguanF ratio = old_base/new_base;
    SguanF result = SGUAN_F(q) * ratio;
    if (result > __LOCAL_Q31_MAX_F0){
        return VALUE_Q31_MAX;
    }
    if (result < -__LOCAL_Q31_MAX_F1){
        return VALUE_Q31_MIN;
    }
    
    if (result >= 0){
        result += VALUE_F_HALF;
    } else{
        result -= VALUE_F_HALF;
    }
    
    return (Q31)result;
}

// (浮点相关的三角局部函数)
static SguanF __local_sin_f(SguanF x){
    while (1){
        if (x > VALUE_F_2PI)
            x = x - VALUE_F_2PI;
        else if (x < 0)
            x = x + VALUE_F_2PI;
        else
            break;
    }

    SguanF pos = x * (SguanF)81.487330863050411914;
    int idx0 = (int)pos;
    SguanF frac = pos - (SguanF)idx0;

    if (idx0 > 511){ idx0 = 511; frac = VALUE_F_ZERO; }
    if (idx0 < 0){ idx0 = 0; frac = VALUE_F_ZERO; }

    int idx1 = idx0 + 1;
    if (idx1 >= 512) idx1 = 0;

    return sin_tab[idx0] + (sin_tab[idx1] - sin_tab[idx0]) * frac;
}

